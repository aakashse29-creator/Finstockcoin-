export function generateInitialCandles(basePrice: number, count = 50): Candle[] {
  const candles: Candle[] = [];
  let currentPrice = basePrice * 0.94;
  const now = Date.now();
  const timeStep = 300000; // 5 min candles

  for (let i = count; i >= 0; i--) {
    const time = now - i * timeStep;
    const variation = (Math.random() - 0.48) * (basePrice * 0.012);
    const open = currentPrice;
    const close = currentPrice + variation;
    const high = Math.max(open, close) + Math.random() * (basePrice * 0.006);
    const low = Math.min(open, close) - Math.random() * (basePrice * 0.006);
    const volume = Math.floor(Math.random() * 50 + 10);
    candles.push({ time, open, high, low, close, volume });
    currentPrice = close;
  }
  return candles;
}
